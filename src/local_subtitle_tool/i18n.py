def translate(text: str, language: str) -> str:
    """Japanese for a Korean UI string when ``language`` is "ja"; otherwise unchanged."""

    if language != "ja" or not text:
        return text
    found = JA.get(text)
    if found is not None:
        return found
    for pattern, replacement in JA_PATTERNS:
        if pattern.fullmatch(text):
            return pattern.sub(replacement, text)
    changed = text
    for pattern, replacement in JA_FRAGMENTS:
        changed = pattern.sub(replacement, changed)
    if changed != text:
        return changed
    if "\n" in text:
        parts = text.split("\n")
        translated = [translate(part, language) for part in parts]
        if translated != parts:
            return "\n".join(translated)
    return text
